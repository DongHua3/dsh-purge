def main() -> int:
    changed = 0
    for fname, old, new in EDITS:
        if old == new:
            continue
        p = MAN / fname
        t = p.read_text(encoding="utf-8")
        n = t.count(old)
        if n == 0:
            print(f"!! 未找到（跳过）: {fname} :: {old[:44]}...")
            continue
        if n > 1:
            print(f"!! 匹配 {n} 处，拒绝替换: {fname} :: {old[:44]}...")
            continue
        p.write_text(t.replace(old, new), encoding="utf-8", newline="\n")
        changed += 1
        print(f"ok {fname} :: {old[:40]}...")
    print(f"\n共完成 {changed} 处替换")
    return 0


if __name__ == "__main__":
    sys.exit(main())
